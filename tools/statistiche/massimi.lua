-- I massimi delle statistiche (Sergio, 15 nov 23:14): la barra di ogni statistica
-- va dalla base al valore più alto che si può avere nel gioco (livello massimo,
-- pezzi al livello 30, Sigilli al massimo). Questo strumento lo cerca e lo scrive
-- in client/menu/stat_max.lua. Dalla radice:
--   luajit tools/statistiche/massimi.lua              (riscrive il file)
--   luajit tools/statistiche/massimi.lua --controlla  (fallisce se non è in pari: gira in tutti.sh)
-- Va rifatto quando cambiano pezzi, Sigilli, livelli o la base: il controllo lo ricorda.
package.path = "client/?.lua;" .. package.path

local game = require "sim.game"
local equip = require "sim.gear"
local skills = require "sim.skills"
local loadout = require "sim.loadout"

local FILE = "client/menu/stat_max.lua"
-- le statistiche con la barra (quelle dove "di più" è meglio)
local STATISTICHE = { "attack", "defense", "max_hp", "walk_speed", "jump_height", "air_speed", "blast_push" }

local base = game.base_stats()
local LIVELLO = skills.LEVEL_MAX

-- tutte le scelte di pezzi: ogni posto vuoto o una famiglia, tutti al livello 30
local function tutti_i_pezzi()
	local out = { {} }
	for _, s in ipairs(equip.SLOTS) do
		local nuovi = {}
		for _, g in ipairs(out) do
			nuovi[#nuovi + 1] = g
			for _, f in ipairs(equip.SETS) do
				if f.pieces[s.id] then
					local c = {}
					for k, v in pairs(g) do c[k] = v end
					c[s.id] = f.id
					nuovi[#nuovi + 1] = c
				end
			end
		end
		out = nuovi
	end
	return out
end

-- tutti gli alberi pieni: due sentieri al massimo (POINTS_MAX = 2 * PATH_MAX) con ogni scelta dei poteri
local function tutti_gli_alberi()
	local out = {}
	local P = skills.PATHS
	local passi = skills.STEPS
	for i = 1, #P do
		for j = i + 1, #P do
			for a = 0, 2 ^ passi - 1 do
				for b = 0, 2 ^ passi - 1 do
					local t = { [P[i].id] = skills.PATH_MAX, [P[j].id] = skills.PATH_MAX, pick = { [P[i].id] = {}, [P[j].id] = {} } }
					for k = 1, passi do
						t.pick[P[i].id][k] = math.floor(a / 2 ^ (k - 1)) % 2 + 1
						t.pick[P[j].id][k] = math.floor(b / 2 ^ (k - 1)) % 2 + 1
					end
					out[#out + 1] = t
				end
			end
		end
	end
	return out
end

local PEZZI, ALBERI = tutti_i_pezzi(), tutti_gli_alberi()

local function livelli(gear)
	local l = {}
	for _, s in ipairs(equip.SLOTS) do l[s.id] = equip.LIVELLO_MAX end
	return l
end

-- il massimo di una statistica: si alternano il miglior albero coi pezzi scelti
-- e i migliori pezzi con l'albero scelto, finché non migliora più
local function massimo(k)
	local gear, tree, best = {}, {}, -math.huge
	for _ = 1, 4 do
		local prima = best
		for _, t in ipairs(ALBERI) do
			local v = loadout.stats(base, { tree = t, gear = gear }, livelli(gear), LIVELLO)[k]
			if v > best then best, tree = v, t end
		end
		for _, g in ipairs(PEZZI) do
			local v = loadout.stats(base, { tree = tree, gear = g }, livelli(g), LIVELLO)[k]
			if v > best then best, gear = v, g end
		end
		if best == prima then break end
	end
	return best
end

local righe = {}
for _, k in ipairs(STATISTICHE) do
	local v = massimo(k)
	righe[#righe + 1] = string.format("\t%s = %s,", k, string.format("%.3f", v):gsub("0+$", ""):gsub("%.$", ""))
end
local testo = "-- GENERATED by tools/statistiche/massimi.lua: do not edit by hand.\n"
	.. "-- The highest value of each stat in the game (player level max, pieces at 30,\n"
	.. "-- Sigilli full): the end of the stat bars (menu/gear_ui.lua).\n"
	.. "return {\n" .. table.concat(righe, "\n") .. "\n}\n"

if arg[1] == "--controlla" then
	local f = io.open(FILE)
	local ora = f and f:read("*a")
	if f then f:close() end
	if ora ~= testo then
		print("FAIL " .. FILE .. " non è in pari coi pezzi e i Sigilli: rifai luajit tools/statistiche/massimi.lua")
		os.exit(1)
	end
	print("ok massimi delle statistiche in pari")
else
	local f = assert(io.open(FILE, "w"))
	f:write(testo)
	f:close()
	io.write(testo)
end

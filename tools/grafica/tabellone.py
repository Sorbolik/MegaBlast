# Il Limbo come tabellone (WB-101 di Codex): taglia dal verde le pedine dell'apprendista e del
# Fabbro, i luoghi del girone e le pietre del sentiero, e scrive
#   client/assets/tabellone/<nome>.png   ogni pezzo al doppio di come lo mostra la campagna
#   client/menu/tabellone.atlas          l'atlante (fuori da /ui: con le mipmap, si vede netto anche piccolo)
#   client/menu/board_pieces.lua         nome -> larghezza e altezza in pixel dell'atlante
# Le misure sullo schermo (pixel del 1280 x 720) sono in LARGO qui sotto; il gioco mostra ogni
# pezzo alla metà della sua misura nell'atlante. Mai ingrandito: se il disegno è più piccolo resta com'è.
#   python3 tools/grafica/tabellone.py     (dalla cartella del repository)
import os, sys
import numpy as np
from PIL import Image
from scipy import ndimage as ndi

QUI = os.path.dirname(os.path.abspath(__file__))
RADICE = os.path.abspath(os.path.join(QUI, "..", ".."))
sys.path.insert(0, QUI)
from fornace import ritaglia, stretto   # noqa: E402

ART = os.path.join(RADICE, "art", "WB-101")
OUT = os.path.join(RADICE, "client", "assets", "tabellone")

# nome nel gioco -> (foglio di Codex, larghezza sullo schermo). Le pedine scelte: la variante 1
# (Claude, 28 nov: le due sono quasi uguali, nella 1 corna e occhialoni sono più netti)
LARGO = {
    "pedina_apprendista": ("pedina_apprendista_1", 31),
    "pedina_fabbro": ("pedina_fabbro_1", 36),
    "limbo_porta": ("limbo_porta", 84),
    "limbo_castello": ("limbo_castello", 200),
    "limbo_castello_acceso": ("limbo_castello_acceso", 200),
    "limbo_bottega": ("limbo_bottega", 70),
    "limbo_ponte": ("limbo_ponte", 86),
    "limbo_prato": ("limbo_prato", 196),
    "limbo_pontile": ("limbo_pontile", 190),
    "limbo_crepa": ("limbo_crepa", 30),
}
# le tre pietre del sentiero sono su un foglio solo, da sinistra a destra: per ora serve solo la
# normale (l'azzurra della porta segreta e quella d'oro delle medaglie aspettano le scorciatoie)
PIETRE = (["pietra", None, None], 22)


def pezzi(im):
    """Gli oggetti di un foglio da sinistra a destra, ognuno ritagliato stretto."""
    a = np.asarray(im.getchannel("A")) > 40
    lab, _ = ndi.label(ndi.binary_dilation(a, iterations=6))
    box = sorted(ndi.find_objects(lab), key=lambda s: s[1].start)
    return [stretto(im.crop((s[1].start, s[0].start, s[1].stop, s[0].stop))) for s in box]


def salva(nome, im, largo, misure):
    w = min(im.width, round(largo * 2))
    if w < im.width:
        im = im.resize((w, max(1, round(im.height * w / im.width))), Image.LANCZOS)
    im.save(os.path.join(OUT, nome + ".png"), optimize=True)
    misure[nome] = im.size


def main():
    os.makedirs(OUT, exist_ok=True)
    misure = {}
    for nome, (foglio, largo) in LARGO.items():
        salva(nome, stretto(ritaglia(os.path.join(ART, foglio + ".png"))), largo, misure)
    nomi, largo = PIETRE
    for nome, im in zip(nomi, pezzi(ritaglia(os.path.join(ART, "limbo_pietre.png")))):
        if nome:
            salva(nome, im, largo, misure)
    with open(os.path.join(RADICE, "client", "menu", "tabellone.atlas"), "w") as f:
        for nome in sorted(misure):
            f.write('images {\n  image: "/assets/tabellone/%s.png"\n}\n' % nome)
        f.write("margin: 2\nextrude_borders: 2\ninner_padding: 0\n")
    with open(os.path.join(RADICE, "client", "menu", "board_pieces.lua"), "w") as f:
        f.write("-- Generated by tools/grafica/tabellone.py: the pieces of the Limbo board (WB-101,\n")
        f.write("-- atlas tabellone), their size in pixels of the atlas: the game shows them at half.\nreturn {\n")
        for nome in sorted(misure):
            w, h = misure[nome]
            f.write("\t%s = { w = %d, h = %d },\n" % (nome, w, h))
        f.write("}\n")
    for nome in sorted(misure):
        print(nome, misure[nome])


main()
